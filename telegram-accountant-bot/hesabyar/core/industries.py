_BY_KEY: dict[str, Industry] = {ind.key: ind for ind in INDUSTRIES}

#: مثال و نکته‌های پیش‌فرض وقتی صنف مشخص نیست.
_GENERIC_EXAMPLE = "امروز ۵۰۰ هزار فروختم"


def all_industries() -> tuple[Industry, ...]:
    return INDUSTRIES


def get(key: str | None) -> Industry | None:
    """پروفایلِ صنف را برمی‌گرداند؛ ``None`` اگر ناشناخته/خالی باشد."""
    if not key:
        return None
    return _BY_KEY.get(key)


def label_for(key: str | None) -> str:
    ind = get(key)
    return ind.label if ind else "نامشخص"


def example_for(key: str | None) -> str:
    """مثالِ ثبتِ تراکنش، متناسب با صنف."""
    ind = get(key)
    return ind.example if ind else _GENERIC_EXAMPLE


def tips_for(key: str | None) -> tuple[str, ...]:
    """نکته‌های مفیدِ همان صنف (ممکن است خالی باشد)."""
    ind = get(key)
    return ind.tips if ind else ()


def refine_category(text: str, kind: str, key: str | None, fallback: str) -> str:
    """اگر متن با دسته‌ای از همان صنف بخورد، آن را برمی‌گرداند؛ وگرنه ``fallback``.

    دسته‌های صنفی بر دسته‌ی عمومی اولویت دارند چون دقیق‌ترند (مثلاً «پژو» در
    نمایشگاه خودرو ⇒ «خرید خودرو» به‌جای «خرید کالا و مواد اولیه»).
    """
    ind = get(key)
    if ind is None or not text:
        return fallback
    table = ind.income if kind == Kind.INCOME else ind.expense
    haystack = text.replace("‌", " ")
    for label, keywords in table:
        for kw in keywords:
            if kw.replace("‌", " ") in haystack:
                return label
    return fallback
